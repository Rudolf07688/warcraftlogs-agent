# --- WCL spec resolution ------------------------------------------------------


async def _resolve_active_spec(
    name: str, server: str, region: str
) -> tuple[str | None, str | None] | None:
    """Best-effort (class, spec) from a character's current-zone rankings.

    Returns ``None`` when the character can't be resolved or has no ranked specs,
    which the caller treats as a ``failed`` guide (entry still saved).
    """
    from wcl_agent.report_tools import get_character_zone_rankings

    res = await get_character_zone_rankings(name, server, region)
    if res.get("status") != "success":
        return None
    zr = res.get("zoneRankings")
    if not isinstance(zr, dict):
        return None
    rankings = zr.get("rankings") or []
    specs = [r.get("spec") for r in rankings if isinstance(r, dict) and r.get("spec")]
    classes = [r.get("class") for r in rankings if isinstance(r, dict) and r.get("class")]
    spec = Counter(specs).most_common(1)[0][0] if specs else None
    cls = Counter(classes).most_common(1)[0][0] if classes else None
    if not spec:
        return None
    return cls, spec


async def _plays_mythic_plus(name: str, server: str, region: str) -> bool:
    """Whether the character has a ranked Mythic+ run this season (FR-030). Best-effort,
    background lane; any failure counts as "no"."""
    from wcl_agent.report_tools import get_character_zone_rankings

    try:
        with background_lane():
            zone = await mplus_zone()
            if not zone:
                return False
            res = await get_character_zone_rankings(
                name, server, region, zone_id=int(zone["id"]), difficulty=MYTHIC_PLUS_DIFFICULTY_ID
            )
    except Exception:  # noqa: BLE001 - optional signal
        logger.warning("Mythic+ activity check failed for %s-%s (%s)", name, server, region)
        return False
    if res.get("status") != "success":
        return False
    zone_rankings = res.get("zoneRankings")
    rankings = zone_rankings.get("rankings") if isinstance(zone_rankings, dict) else None
    return any(
        isinstance(r, dict) and r.get("spec") and (r.get("totalKills") or 0) > 0
        for r in rankings or []
    )


async def resolve_active_spec(
    name: str, server: str, region: str
) -> tuple[str | None, str | None] | None:
    """Best-effort spec resolution in the background lane (FR-024): guide work never takes
    WCL slots a chat lookup is waiting for."""
    try:
        with background_lane():
            return await _resolve_active_spec(name, server, region)
    except Exception:  # noqa: BLE001 - resolution is best-effort
        logger.exception("Active-spec resolution failed for %s-%s (%s)", name, server, region)
        return None


# --- Guide / summary text generation -----------------------------------------


@dataclass(frozen=True)
class GeneratedText:
    """Model output plus the web-grounding sources it used (feature 009, research R9)."""

    text: str
    sources: list[dict]  # [{title, uri}] — deterministic, from grounding records
    session_id: str


# PERF-012: one semaphore per event loop (tests run several loops) caps how many
# background generations run at once.
_generation_slots: dict[asyncio.AbstractEventLoop, asyncio.Semaphore] = {}


def _generation_slot() -> asyncio.Semaphore:
    loop = asyncio.get_running_loop()
    slot = _generation_slots.get(loop)
    if slot is None:
        slot = _generation_slots[loop] = asyncio.Semaphore(max(1, settings.wcl_guide_max_concurrency))
    return slot


async def _generate_text(prompt: str, session_id: str | None = None) -> GeneratedText:
    """Run ``prompt`` through the guide model over a disposable session; collect text.

    ``session_id`` is reused when given (the guide-meta repair turn), else a fresh
    disposable session is created. Sources come from the ``grounding`` records
    ``stream_response`` emits (empty when the model has no web search). At most
    ``wcl_guide_max_concurrency`` generations run at once (PERF-012).
    """
    async with _generation_slot():
        return await _stream_text(prompt, session_id)


async def _stream_text(prompt: str, session_id: str | None) -> GeneratedText:
    from ..agent_runner import stream_response

    session_id = session_id or f"guide-{uuid.uuid4().hex}"
    tokens: list[str] = []
    sources: list[dict] = []
    seen: set[str] = set()
    async for record in stream_response(settings.wcl_guide_model, session_id, prompt):
        kind = record.get("type")
        if kind == "token":
            tokens.append(record["text"])
        elif kind == "grounding":
            for src in record.get("sources") or []:
                uri = src.get("uri") if isinstance(src, dict) else None
                if uri and uri not in seen:
                    seen.add(uri)
                    sources.append({"title": src.get("title"), "uri": uri})
    return GeneratedText("".join(tokens).strip(), sources, session_id)


# --- Coaching briefs for the agent (feature 015, data-model §5) ---------------------
# ``wcl_agent`` reads briefs through ``guide_meta.get_brief``; this module registers the
# loader. Briefs come from the PUBLISHED columns only (never a draft) and are cached in this
# process for a minute, so a guide published by another instance is seen within a minute.

_BRIEF_TTL_S = 60.0
_brief_cache: dict[tuple[str, str, str], tuple[float, BriefRecord | None]] = {}


def invalidate_brief_cache(key: tuple[str, str, str] | None = None) -> None:
    """Forget one cached brief (after a publish in this process), or all of them."""
    if key is None:
        _brief_cache.clear()
    else:
        _brief_cache.pop(key, None)


def guide_freshness_of(
    content_type: str,
    game_patch: str | None,
    season: str | None,
    stale_reason: str | None,
    live_patch: str | None,
    live_season: str | None,
) -> str:
    """Read-time freshness of a published guide: the stored patch against live, a stale
    mark from the scan, and for Mythic+ the season (data-model §2)."""
    freshness = guide_freshness(game_patch, live_patch)
    if freshness != "current":
        return freshness
    if stale_reason:
        return "possibly_stale"
    if content_type == "mplus" and live_season and season != live_season:
        return "possibly_stale"
    return "current"


def _cooldowns_of(brief: CoachingBrief) -> tuple[GuideCooldown, ...]:
    return tuple(
        GuideCooldown(name=c.name, spell_id=c.ability_id, cooldown_s=float(c.cooldown_s), charges=c.charges)
        for c in brief.cooldowns
        if c.cooldown_s
    )


async def _live_context(content_type: str) -> tuple[str | None, str | None]:
    with background_lane():
        live_patch = await current_patch()
        live_season = await current_mplus_season() if content_type == "mplus" else None
    return live_patch, live_season


async def load_brief_record(class_name: str, spec: str, content_type: str) -> BriefRecord | None:
    """The brief loader registered with ``wcl_agent.guide_meta`` (published briefs only)."""
    entry = resolve_spec(class_name, spec)
    if entry is None or content_type not in ("raid", "mplus"):
        return None
    key = (entry.class_name, entry.spec, content_type)
    cached = _brief_cache.get(key)
    if cached is not None and time.monotonic() - cached[0] < _BRIEF_TTL_S:
        return cached[1]
    async with db_session.SessionLocal() as session:
        row = await repo.get_spec_guide(
            session, class_name=entry.class_name, spec=entry.spec, content_type=content_type
        )
    record = None
    if row is not None and row.brief:
        brief = CoachingBrief.model_validate(row.brief)
        live_patch, live_season = await _live_context(content_type)
        freshness = guide_freshness_of(
            content_type, row.game_patch, row.season, row.stale_reason, live_patch, live_season
        )
        record = BriefRecord(
            class_name=entry.class_name,
            spec=entry.spec,
            content_type=content_type,
            text=render_brief_text(brief, freshness),
            cooldowns=_cooldowns_of(brief),
            game_patch=row.game_patch,
            season=row.season,
            generated_at=row.generated_at,
            freshness=freshness,
            data_sufficient=brief.data_sufficient,
        )
    _brief_cache[key] = (time.monotonic(), record)
    return record


@dataclass(frozen=True)
class TurnBriefs:
    """The coaching briefs one chat turn carries (contracts/agent-context.md §2.1)."""

    content_type: str  # raid | mplus — the type the turn is about (raid when unclear)
    note: str | None  # set when the type was assumed rather than recognised
    briefs: dict[tuple[str, str], BriefRecord]  # published briefs of that type, per spec
    available: dict[tuple[str, str], dict[str, bool]]  # per spec: {type: has a published brief}


_ASSUMED_NOTE = "assumed Raid — the message did not say; ask if it is about Mythic+"


async def briefs_for_turn(
    specs: list[tuple[str, str]], user_text: str, recent_zone_name: str | None
) -> TurnBriefs:
    """Pick the turn's content type and fetch each profile spec's brief of that type.

    Both content types are looked up (through the cached loader) so the index can say
    where the other type's brief is; only the chosen type's briefs are returned for
    inlining. A Mythic+ question never gets a Raid brief, and the reverse (FR-014).
    """
    try:
        with background_lane():
            zones = await load_world_zones()
    except Exception as exc:  # noqa: BLE001 - QA BUG-001: classify from the message alone
        logger.warning("zone list unavailable for the turn's content type: %s", exc)
        zones = []
    mplus = mplus_zone_from(zones) or {}
    raid = raid_zone_from(zones) or {}
    guess = classify_content_type(
        user_text,
        recent_zone_name,
        mplus.get("name"),
        [e.get("name", "") for e in mplus.get("encounters") or []],
        [e.get("name", "") for e in raid.get("encounters") or []],
    )
    content_type = "raid" if guess == "unknown" else guess
    note = _ASSUMED_NOTE if guess == "unknown" else None
    briefs: dict[tuple[str, str], BriefRecord] = {}
    available: dict[tuple[str, str], dict[str, bool]] = {}
    for key in dict.fromkeys(specs):
        found = {ct: await get_brief(*key, ct) for ct in ("raid", "mplus")}
        available[key] = {ct: record is not None for ct, record in found.items()}
        if found[content_type] is not None:
            briefs[key] = found[content_type]
    maybe_scan_stale_guides()
    touch_guide_wanted([(r.class_name, r.spec, r.content_type) for r in briefs.values()])
    return TurnBriefs(content_type, note, briefs, available)


# --- Shared spec-guide library (feature 008 / US2) ----------------------------
# One guide per (class, spec) in the GLOBAL ``spec_guides`` table, shared by all users.
# Reuses the same off-loop generation path as the per-character guide (Principle I —
# no second generation path) and the same ``background.spawn`` dedup/GC machinery, re-keyed to
# the ``(class, spec)`` pair. Uses a plain (non-tenant) session: the table is global.


async def ensure_guide(
    class_name: str, spec: str, content_type: str = "raid", *, force: bool = False
) -> None:
    """Idempotent, best-effort generation of one ``(class, spec, content_type)`` guide.

    - ``ready`` & not stale & not ``force``, or ``pending`` → no-op (dedup; FR-013, SC-004).
    - absent | ``failed`` | ``needs_review`` | stale | ``force`` → upsert ``pending``, spawn
      the pipeline run (published / held for review / failed — always retryable).

    Never raises into the caller.
    """
    try:
        async with db_session.SessionLocal() as session:
            existing = await repo.get_spec_guide(
                session, class_name=class_name, spec=spec, content_type=content_type
            )
            if existing is not None and existing.status == "pending" and not pending_abandoned(existing):
                return  # generation already in flight
            if existing is not None and existing.status == "ready" and not force and not existing.stale_reason:
                return  # dedup — reuse the ready, current guide
            try:
                await repo.upsert_spec_guide(
                    session,
                    class_name=class_name,
                    spec=spec,
                    content_type=content_type,
                    status="pending",
                )
                await session.commit()
            except IntegrityError:
                # A concurrent insert won the unique (class, spec, type) race; it owns
                # generation. Read nothing more — no-op.
                await session.rollback()
                return
    except Exception:  # noqa: BLE001 - scheduling is best-effort, never breaks the caller
        logger.exception(
            "ensure_guide bookkeeping failed for %s %s %s", class_name, spec, content_type
        )
        return

    spawn(_run_guide(class_name, spec, content_type), (class_name, spec, content_type))


async def _run_guide(class_name: str, spec: str, content_type: str) -> None:
    """One pipeline run under the generation cap (PERF-012); never raises."""
    async with _generation_slot():
        await run_guide_generation(class_name, spec, content_type)
    invalidate_brief_cache((class_name, spec, content_type))


def summarize_guide(
    row, content_type: str, live_patch: str | None, live_season: str | None
) -> dict:
    """One content type's library summary (``GuideSummary``) from a row, or "none" (FR-026)."""
    if row is None:
        return {"content_type": content_type, "status": "none"}
    published = repo.guide_has_published(row)
    return {
        "content_type": content_type,
        "status": row.status,
        "has_published": published,
        "refreshing": row.status == "pending" and published,
        "game_patch": row.game_patch if published else None,
        "season": row.season if published else None,
        "generated_at": row.generated_at if published else None,
        "updated_at": row.updated_at,
        "freshness": (
            guide_freshness_of(
                content_type, row.game_patch, row.season, row.stale_reason, live_patch, live_season
            )
            if published
            else None
        ),
        "stale_reason": row.stale_reason if published else None,
    }


def build_guide_roster(
    guides: list, live_patch: str | None = None, live_season: str | None = None
) -> list[dict]:
    """Merge the full live roster (``wcl_agent.roster``) with ``spec_guides`` rows (FR-008).

    Every class+spec appears exactly once (100% coverage, SC-002; FR-028) with a summary
    for each content type; a missing row reports ``status="none"``. Ordered by class
    display name, then spec.
    """
    by_key = {(g.class_name, g.spec, g.content_type): g for g in guides}
    items: list[dict] = []
    for entry in roster_snapshot().specs:
        items.append(
            {
                "class_name": entry.class_name,
                "class_display": entry.class_display,
                "spec": entry.spec,
                "spec_display": entry.spec_display,
                "role": entry.role,
                **{
                    ct: summarize_guide(
                        by_key.get((entry.class_name, entry.spec, ct)), ct, live_patch, live_season
                    )
                    for ct in ("raid", "mplus")
                },
            }
        )
    items.sort(key=lambda it: (it["class_display"], it["spec"]))
    return items


# --- Staleness and the in-use rule (feature 015, FR-050/FR-051) ----------------------------

STALE_SCAN_EVERY_S = 600.0
WANTED_STAMP_EVERY_S = 3600.0
# QA SPEC-002/BUG-003/PERF-002: after an automatic run ends held or failed, wait this long
# before trying the same stale guide again (otherwise every scan and open reruns it).
AUTO_RETRY_BACKOFF = timedelta(hours=24)
# QA BUG-002: a run "pending" this long was interrupted (restart, deploy, crash).
PENDING_ABANDONED = timedelta(minutes=45)
# QA PERF-001: regenerations one scan may start (most recently wanted first), so a patch
# day or the first deploy does not spend the WCL points budget chat lookups need.
MAX_REGENERATIONS_PER_SCAN = 3
# Postponed runs that should be retried on the next scan, not after the backoff.
_RETRY_SOON = frozenset({"wcl_budget"})
_last_scan: float | None = None
_last_stamp: dict[tuple[str, str, str], float] = {}


def _patch_older(stored: str | None, live: str | None) -> bool:
    """The stored patch is behind live: exact ``major.minor.patch`` when both give it,
    else ``major.minor`` (the WCL fallback only knows that much)."""
    if not stored or not live:
        return False
    a, b = stored.split("."), live.split(".")
    if len(a) >= 3 and len(b) >= 3:
        try:
            return tuple(int(x) for x in a[:3]) < tuple(int(x) for x in b[:3])
        except ValueError:
            return False
    return guide_freshness(stored, live) == "possibly_stale"


def compute_stale_reason(
    *,
    content_type: str,
    class_name: str,
    spec: str,
    game_patch: str | None,
    season: str | None,
    generated_at: datetime | None,
    current_reason: str | None,
    live_patch: str | None,
    live_season: str | None,
    hotfix_at: datetime | None,
    hotfix_touches: bool,
) -> str | None:
    """Why a published guide is out of date, or None (contracts/guide-pipeline.md §Staleness)."""
    if current_reason == "legacy":
        return "legacy"  # pre-feature guides stay marked until regenerated (FR-055)
    if _patch_older(game_patch, live_patch):
        return "patch_changed"
    if content_type == "mplus" and live_season and season != live_season:
        return "season_changed"
    if hotfix_touches and hotfix_at and generated_at and _aware(hotfix_at) > _aware(generated_at):
        return "hotfix"
    return current_reason


def _aware(value: datetime) -> datetime:
    """Timestamps read back without a zone (SQLite) are UTC."""
    return value if value.tzinfo else value.replace(tzinfo=UTC)


def _since(value: datetime | None, now: datetime) -> timedelta | None:
    return now - _aware(value) if value else None


def pending_abandoned(row, now: datetime | None = None) -> bool:
    """A ``pending`` row whose run stopped without recording an outcome."""
    age = _since(getattr(row, "updated_at", None), now or datetime.now(UTC))
    return row.status == "pending" and age is not None and age > PENDING_ABANDONED


def recently_attempted(row, now: datetime | None = None) -> bool:
    """The latest run ended held or failed within the backoff window."""
    if row.status not in ("failed", "needs_review") or row.failure_reason in _RETRY_SOON:
        return False
    age = _since(getattr(row, "updated_at", None), now or datetime.now(UTC))
    return age is not None and age < AUTO_RETRY_BACKOFF


def _may_auto_regenerate(row, now: datetime) -> bool:
    if row.status == "pending":
        return pending_abandoned(row, now)
    return not recently_attempted(row, now)


def _in_use(row, now: datetime) -> bool:
    if row.last_wanted_at is None:
        return False
    return now - _aware(row.last_wanted_at) <= timedelta(days=settings.wcl_guide_inuse_days)


async def scan_stale_guides() -> int:
    """Mark published guides stale and regenerate the ones in use. Returns how many rows
    changed; never raises."""
    from .guide_pipeline.briefing import fetch_hotfix_feed, fetch_live_version, hotfix_touch_time

    try:
        version = await fetch_live_version()
        with background_lane():
            live_patch = version.patch if version else await current_patch()
            live_season = await current_mplus_season()
        feed = await fetch_hotfix_feed()
        async with db_session.SessionLocal() as session:
            rows = await repo.list_spec_guides(session, with_text=False)
    except Exception:  # noqa: BLE001 - best-effort background work
        logger.exception("stale scan could not read its inputs")
        return 0
    now = datetime.now(UTC)
    marks: dict[tuple[str, str, str], str] = {}
    regenerate: list[tuple[datetime, tuple[str, str, str]]] = []
    for row in rows:
        if not repo.guide_has_published(row):
            continue
        reason = compute_stale_reason(
            content_type=row.content_type,
            class_name=row.class_name,
            spec=row.spec,
            game_patch=row.game_patch,
            season=row.season,
            generated_at=row.generated_at,
            current_reason=row.stale_reason,
            live_patch=live_patch,
            live_season=live_season,
            hotfix_at=hotfix_touch_time(feed, row.class_name, row.spec),
            hotfix_touches=True,
        )
        key = (row.class_name, row.spec, row.content_type)
        if reason and reason != row.stale_reason:
            marks[key] = reason
        if reason and _in_use(row, now) and _may_auto_regenerate(row, now):
            regenerate.append((row.last_wanted_at, key))
    if marks:
        async with db_session.SessionLocal() as session:
            await repo.set_guide_stale(session, marks)
            await session.commit()
    regenerate.sort(key=lambda item: _aware(item[0]), reverse=True)
    regenerate = regenerate[:MAX_REGENERATIONS_PER_SCAN]
    for _, key in regenerate:
        await ensure_guide(*key, force=True)
    if marks or regenerate:
        logger.info("stale scan: %d marked, %d in-use guides regenerating", len(marks), len(regenerate))
    return len(marks)


def maybe_scan_stale_guides() -> None:
    """Start a stale scan in the background at most every 10 minutes (no scheduler: the
    library, the chat preamble and startup trigger it). Non-blocking."""
    global _last_scan
    now = time.monotonic()
    if _last_scan is not None and now - _last_scan < STALE_SCAN_EVERY_S:
        return
    _last_scan = now
    spawn(scan_stale_guides(), "stale-scan")


def touch_guide_wanted(keys: list[tuple[str, str, str]]) -> None:
    """Stamp ``last_wanted_at`` (at most hourly per guide), in the background."""
    now = time.monotonic()
    due = [k for k in dict.fromkeys(keys) if now - _last_stamp.get(k, -WANTED_STAMP_EVERY_S) >= WANTED_STAMP_EVERY_S]
    if not due:
        return
    for key in due:
        _last_stamp[key] = now

    async def stamp() -> None:
        try:
            async with db_session.SessionLocal() as session:
                await repo.touch_guides_wanted(session, due, datetime.now(UTC))
                await session.commit()
        except Exception:  # noqa: BLE001 - bookkeeping only
            logger.exception("last_wanted_at stamp failed")

    spawn(stamp(), ("wanted", *due[0], len(due), now))


def stale_and_idle(row) -> bool:
    """A published, stale guide to regenerate on open (FR-051): not already running, and
    not just held or failed (the same backoff as the scan)."""
    if not (row and repo.guide_has_published(row) and row.stale_reason):
        return False
    return _may_auto_regenerate(row, datetime.now(UTC))


