"""Write the Mimir cost rules from the price table (feature 055, sc-410).

  uv run python observability/pricing/generate.py           # rewrite cost.yaml
  uv run python observability/pricing/generate.py --check   # exit 1 if cost.yaml is stale

pricing.yaml (USD per million tokens) becomes one recording rule per model and token type,
`llm_price_usd_per_token{gen_ai_request_model, gen_ai_token_type}`, a constant Mimir records
every minute: the price history is a time series, so a price change applies from the moment
the new rules load and cost already computed keeps the old price. In the same group (evaluated
in order, after the prices) `genai:cost_usd:rate5m` joins the backend's token usage to them.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PRICING = HERE / "pricing.yaml"
RULES = HERE.parent / "mimir" / "rules" / "anonymous" / "cost.yaml"

# Token usage is a native (exponential) histogram, so its sum comes from histogram_sum. Dated
# model ids are priced as their undated row. USD per second by model and agent (board
# contract:cost-alias); a model without a price row has no cost series (not zero).
COST_EXPR = """sum by (gen_ai_request_model, gen_ai_agent_name) (
  label_replace(
    histogram_sum(rate(gen_ai_client_token_usage[5m])),
    "gen_ai_request_model", "$1", "gen_ai_request_model", "(.+?)(?:@\\\\d{8}|-\\\\d{8})?"
  )
  * on (gen_ai_request_model, gen_ai_token_type) group_left
  llm_price_usd_per_token
)
"""

HEADER = """\
# GENERATED by observability/pricing/generate.py from observability/pricing/pricing.yaml.
# Do not edit: change pricing.yaml and run the generator (feature 055, sc-410, spec §6.5).
"""


def per_token(usd_per_million: float) -> str:
    return f"{usd_per_million / 1e6:.6e}"


def render(pricing: dict) -> str:
    rules = []
    for model, prices in pricing["models"].items():
        for token_type, usd in prices.items():
            rules.append({"record": "llm_price_usd_per_token", "expr": f"vector({per_token(float(usd))})",
                          "labels": {"gen_ai_request_model": model, "gen_ai_token_type": token_type}})
    rules.append({"record": "genai:cost_usd:rate5m", "expr": COST_EXPR})
    doc = {"groups": [{"name": "llm-cost", "interval": "1m", "rules": rules}]}

    class Literal(yaml.SafeDumper):
        pass

    Literal.add_representer(str, lambda d, s: d.represent_scalar(
        "tag:yaml.org,2002:str", s, style="|" if "\n" in s else None))
    return HEADER + yaml.dump(doc, Dumper=Literal, sort_keys=False, width=200)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if cost.yaml differs from pricing.yaml")
    a = ap.parse_args()
    text = render(yaml.safe_load(PRICING.read_text()))
    if a.check:
        if RULES.read_text() != text:
            print(f"{RULES} is stale: run observability/pricing/generate.py", file=sys.stderr)
            return 1
        return 0
    RULES.write_text(text)
    print(f"wrote {RULES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
